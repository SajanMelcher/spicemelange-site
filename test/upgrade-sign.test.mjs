import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { Ed25519Keypair } from '@mysten/sui/keypairs/ed25519';
import { bcs } from '@mysten/sui/bcs';
import { handleUpgradeSign, checkShape, sha256Hex, EXPECT } from '../store-core/upgrade-sign.js';
import { wranglerVar } from '../scripts/wrangler-var.mjs';
const TX = JSON.parse(readFileSync(new URL('../store-core/upgrade-tx.json', import.meta.url), 'utf8'));
const U8 = Uint8Array.from(Buffer.from(TX.txBytesB64, 'base64'));
const ENV = { SPICE_CERT_PREVIEW: '1', UPGRADE_SIGN_ENABLED: '1', UPGRADE_REVIEWED_SHA256: TX.sha256 };
const sim = (status = 'SUCCESS') => async (_u, o) => { const q = JSON.parse(o.body).query; assert.doesNotMatch(q, /mutation/, 'no execute in this test'); return { json: async () => ({ data: { simulateTransaction: { effects: { status, executionError: null } } } }) }; };
const call = (a, env, body, f = sim()) => handleUpgradeSign(a, { env, request: new Request('https://x/api/upgrade-sign/' + a, body ? { method: 'POST', body: JSON.stringify(body) } : {}) }, f).then(async (r) => [r.status, await r.json()]);

test('generated bytes hash to their recorded sha and have exactly the reviewed shape', async () => {
  assert.equal(await sha256Hex(U8), TX.sha256);
  const s = checkShape(U8);
  assert.equal(s.sender, EXPECT.sender); assert.equal(s.package, EXPECT.package); assert.equal(s.upgradeCap, EXPECT.upgradeCap); assert.ok(s.gasBudgetSui <= 0.06);
});
test('shape check refuses a different sender, package or extra command', () => {
  const t = bcs.TransactionData.parse(U8);
  const bad = (mut) => { const c = structuredClone(t); mut(c.V1); return bcs.TransactionData.serialize(c).toBytes(); };
  assert.throws(() => checkShape(bad((v) => { v.sender = '0x' + '1'.repeat(64); })), /sender/);
  assert.throws(() => checkShape(bad((v) => { v.kind.ProgrammableTransaction.commands[1].Upgrade.package = '0x' + '2'.repeat(64); })), /another package/);
  assert.throws(() => checkShape(bad((v) => { v.kind.ProgrammableTransaction.commands.push(v.kind.ProgrammableTransaction.commands[0]); })), /commands/);
  assert.throws(() => checkShape(bad((v) => { v.gasData.budget = '900000000'; })), /budget/);
});
test('off unless (preview or WALLET_PAGES_LIVE) and UPGRADE_SIGN_ENABLED; prod pins only the reviewed sha', async () => {
  assert.equal((await call('tx', {}))[0], 404);
  assert.equal((await call('tx', { ...ENV, SPICE_CERT_PREVIEW: '0' }))[0], 404);
  assert.equal((await call('tx', { UPGRADE_SIGN_ENABLED: '1', UPGRADE_REVIEWED_SHA256: TX.sha256, WALLET_PAGES_LIVE: '1' }))[0], 200);
  const toml = readFileSync(new URL('../wrangler.toml', import.meta.url), 'utf8');
  assert.equal(wranglerVar(toml, 'WALLET_PAGES_LIVE', 'production'), '0', 'prod flag OFF until Siona + Cloudflare Access');
  for (const e of ['production', 'preview']) assert.equal(wranglerVar(toml, 'UPGRADE_REVIEWED_SHA256', e), TX.sha256);
  assert.equal(TX.sha256, 'e000df0ffd6f7cd271a691fffe77dc0eeb324c7df9cc4704c6db2b6799dc6566');
  assert.equal(checkShape(U8).txDigest, '37bSrXhV5D5bfmtNtLdh9gHjPpNpos3koYJ5JQC9iwLw');
});
test('serves bytes only when their sha is reviewed; reports stale simulation', async () => {
  const [st, r] = await call('tx', { ...ENV, UPGRADE_REVIEWED_SHA256: 'ab'.repeat(32) });
  assert.equal(st, 409); assert.equal(r.reason, 'not_reviewed');
  const [s2, ok] = await call('tx', ENV); assert.equal(s2, 200); assert.equal(ok.txBytesB64, TX.txBytesB64); assert.equal(ok.sha256, TX.sha256); assert.equal(ok.simulation.status, 'SUCCESS');
  const [, stale] = await call('tx', ENV, null, sim('FAILURE')); assert.equal(stale.simulation.status, 'FAILURE');
});
test('no server relay: execute (sign-then-server-submit) does not exist', async () => {
  const [st] = await call('execute', ENV, { txBytesB64: TX.txBytesB64, signature: 'x' }); assert.equal(st, 405);
  assert.doesNotMatch(readFileSync(new URL('../store-core/upgrade-sign.js', import.meta.url), 'utf8'), /executeTransaction|verifyTransactionSignature/);
});
