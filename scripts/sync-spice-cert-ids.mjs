// Single source of truth for the testnet Spice Certificate ids used by the site: copies the public ids from the Ixians'
// deploy files into store-core/spice-cert-testnet.json (no keys, no config paths). Run after every testnet republish:
//   node scripts/sync-spice-cert-ids.mjs [/workspace/ixians/spice-certificates]
// The test suite fails if the JSON and the deploy files disagree (when the deploy files are present).
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
const dir = process.argv[2] || '/workspace/ixians/spice-certificates';
export function pick(d) {
  return { packageId: d.packageId, issuerId: d.issuerId, certificateType: `${d.packageId}::certificate::SpiceCertificate`,
    deskLicenseType: d.deskLicenseType, coinType: d.coinType, price: String(d.price), payee: d.payee,
    allowedTemplates: d.allowedTemplates || ['dune-saga-collection'], publishDigest: d.publishDigest,
    design: String(d.design || '').split(':')[0], originalPackageId: d.originalPackageId || d.packageId,
    // v4: payment_ref is the canonical raw 32-byte tx digest (purchase records ctx.digest(); the watcher path must pass exactly 32 bytes).
    paymentRefLen: String(d.design || '').startsWith('v4') ? 32 : null };
}
export function build(dir) {
  const c = JSON.parse(readFileSync(`${dir}/deploy.testnet.json`, 'utf8'));
  const e = JSON.parse(readFileSync(`${dir}/deploy.testnet-e2e.json`, 'utf8'));
  return { _comment: 'GENERATED by scripts/sync-spice-cert-ids.mjs from the Ixians deploy files. Do not edit by hand. TESTNET ONLY.',
    network: 'testnet', chain: 'sui:testnet', design: pick(c).design, buy: pick(c), holders: pick(e),
    // mainnet ids (redemption request switch SPICE_CERT_REDEEM_NETWORK=mainnet) appear only once deploy.mainnet.json exists
    ...(existsSync(`${dir}/deploy.mainnet.json`) ? { mainnet: (({ packageId, issuerId, certificateType, design, originalPackageId }) => ({ packageId, issuerId, certificateType, design, originalPackageId }))(pick(JSON.parse(readFileSync(`${dir}/deploy.mainnet.json`, 'utf8')))) } : {}) };
}
if (import.meta.url === `file://${process.argv[1]}`) {
  const out = build(dir);
  writeFileSync(new URL('../store-core/spice-cert-testnet.json', import.meta.url), JSON.stringify(out, null, 2) + '\n');
  console.log('wrote store-core/spice-cert-testnet.json', out.buy.packageId, out.holders.packageId);
}
